#!/usr/bin/env python3
"""Emit cron (when provably equivalent) or a Timetable data file per scheduled job [spec §7.1].
See reference/calendars-and-scheduling.md for the rules this implements.

Deterministic: given the same manifest, output is byte-identical.
Reads the manifest and writes local files only; never contacts a live AutoSys or Astro system.

Only emits a cron string when `manifest.schedules[key].cron_expressible` is true (computed by
`calendar_expand.py`'s `_lib.autosys_jil.calendars.cron_equivalent()`, which proves exact fire-
date equivalence over a horizon) -- never derives cron from attribute presence by eye.

Usage:
    python3 translate_calendars.py --manifest estate_manifest.json --out include/calendars/ [--md calendar_decisions.md]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

_LIB = Path(__file__).resolve().parents[2] / "_lib"
sys.path.insert(0, str(_LIB))

from autosys_jil import manifest as manifest_mod  # noqa: E402

_TIMETABLE_STUB_TEMPLATE = '''"""Timetable stub for {job} ({instance}), generated by translate_calendars.py.

Source calendar class: {calendar_class}. This job's schedule is NOT cron-expressible -- see
reference/calendars-and-scheduling.md. Fill in the actual date-list-driven Timetable using the
sibling include/calendars/{job}.txt file (the extracted date list) and the shipped
include/timetables/date_list_timetable.py base class in the fixture Astro project.
"""
# TODO(JUDG:timetable): wire this DAG's `schedule=` to a DateListTimetable reading
# include/calendars/{job}.txt, or implement the underlying rule in code if the calendar
# genuinely follows one (see _lib.autosys_jil.calendars.classify_calendar()).
'''


def compute_decisions(estate) -> dict[str, dict]:
    decisions: dict[str, dict] = {}
    for key, sched in (estate.schedules or {}).items():
        if sched.get("cron_expressible"):
            decisions[key] = {"decision": "cron", "value": sched["cron"], "reason": "cron_equivalent() proved exact fire-date equivalence over the horizon"}
        else:
            decisions[key] = {"decision": "timetable", "value": None,
                              "calendar_class": sched.get("calendar_class"),
                              "reason": "not cron-expressible -- calendar/run_window/non-trivial schedule"}
    return decisions


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--md", type=Path, default=None)
    args = ap.parse_args(argv)

    if not args.manifest.exists():
        print(f"error: {args.manifest} not found -- run build_estate_manifest.py first", file=sys.stderr)
        return 1

    estate = manifest_mod.from_json(args.manifest)
    if not estate.schedules:
        print("error: manifest has no schedules{} -- run calendar_expand.py first", file=sys.stderr)
        return 1

    decisions = compute_decisions(estate)
    args.out.mkdir(parents=True, exist_ok=True)

    cron_count = 0
    timetable_count = 0
    for key, d in decisions.items():
        _, _, job_name = key.partition(":")
        if d["decision"] == "cron":
            cron_count += 1
            continue
        timetable_count += 1
        stub = _TIMETABLE_STUB_TEMPLATE.format(job=job_name, instance=key.split(":")[0],
                                               calendar_class=d.get("calendar_class") or "unknown")
        (args.out / f"{job_name}_timetable_stub.py").write_text(stub)

    if args.md:
        lines = ["# Calendar decisions", "", "| Job | Decision | Value/Class |", "|---|---|---|"]
        for key, d in decisions.items():
            lines.append(f"| {key} | {d['decision']} | {d.get('value') or d.get('calendar_class') or ''} |")
        args.md.write_text("\n".join(lines) + "\n")

    print(f"wrote {args.out}: {cron_count} cron-expressible, {timetable_count} need a Timetable "
          f"(stubs written)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
